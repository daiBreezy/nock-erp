/** a session note (3–5 paragraphs) that matches the class's subject; `i` rotates through the few written for it */
export const sampleSessionNote = (subject: string | undefined, i: number): string => {
  const list = (subject && NOTES[subject]) || NOTES_GENERAL
  return list[i % list.length]
}
